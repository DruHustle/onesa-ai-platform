"""Generate frontend API types from the unchanged, checked-in OpenAPI contract."""

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "onesa-ai-platform-frontend/packages/api-client/contracts.ts"


def typescript(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for key in ("anyOf", "oneOf", "allOf"):
        if key in schema:
            join = " & " if key == "allOf" else " | "
            return "(" + join.join(typescript(item) for item in schema[key]) + ")"
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        required = schema.get("required", [])
        fields = [
            f"{json.dumps(name)}{'' if name in required else '?'}: {typescript(value)};"
            for name, value in schema.get("properties", {}).items()
        ]
        extra = schema.get("additionalProperties")
        if extra:
            fields.append(
                f"[key: string]: {typescript(extra) if isinstance(extra, dict) else 'unknown'};"
            )
        return "{ " + " ".join(fields) + " }" if fields else "Record<string, unknown>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generate() -> str:
    spec = json.loads((ROOT / "docs/api/openapi.json").read_text())
    lines = ["// Generated by scripts/generate_api_client.py; do not edit."]
    for name, schema in sorted(spec["components"]["schemas"].items()):
        lines.append(f"export type {name} = {typescript(schema)};")
    lines.append("export interface Operations {")
    for path, methods in sorted(spec["paths"].items()):
        if not path.startswith("/api/v1/"):
            continue
        for method, operation in sorted(methods.items()):
            if method not in {"get", "post", "patch", "delete", "put"}:
                continue
            body = (
                operation.get("requestBody", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema", {})
            )
            success = next(
                (
                    value
                    for code, value in operation["responses"].items()
                    if code.startswith("2")
                ),
                {},
            )
            response = (
                success.get("content", {}).get("application/json", {}).get("schema", {})
            )
            key = method.upper() + " " + path.removeprefix("/api/v1")
            lines.append(
                f"  {json.dumps(key)}: {{ body: {typescript(body) if body else 'undefined'}; response: {typescript(response) if response else 'void'} }};"
            )
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit("API client contract drift; run make api-client")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content)
