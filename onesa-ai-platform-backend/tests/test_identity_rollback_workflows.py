"""Run the owner rollback's exact API workflow program on isolated PostgreSQL.

These tests do not substitute for executing the exact retained ARM64 image.
The existing pg fixture requires a disposable database whose name ends in _test.
"""

import importlib.util
from pathlib import Path
from uuid import uuid4

import pytest
from alembic import command
from alembic.config import Config
from cryptography.fernet import Fernet
from fastapi.testclient import TestClient
from sqlalchemy import create_engine, inspect, text

from app.config import Settings
from app.database import REQUIRED_SCHEMA_REVISION
from app.main import create_app


def workflow():
    path = Path(__file__).resolve().parents[2] / "scripts/release/oracle_identity_rollback.py"
    spec = importlib.util.spec_from_file_location("owner_identity_rollback", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    # PROGRAM supplies this import before the exact shared workflow body. Use the
    # real application here too; an empty exec namespace cannot run the proof.
    namespace = {"create_app": create_app}
    exec(compile(module.WORKFLOWS, str(path), "exec"), namespace)
    return namespace["exercise"]


def test_rollback_workflow_requires_ready_database_before_seeding():
    settings = Settings(
        environment="test",
        database_url=None,
        model_backend="mock",
        identity_enabled=False,
        digital_twins_enabled=False,
        cybersecurity_enabled=False,
    )
    with pytest.raises(AssertionError):
        workflow()(settings, {"phase": "seed", "enabled_features": [], "fixture": None})


@pytest.fixture
def bridge_database(pg, monkeypatch):
    """An actually historical schema, isolated from the suite's head database."""
    assert (pg.url.database or "").endswith("_test")
    name = "onesa_identity_bridge_" + uuid4().hex + "_test"
    database = None
    created = False
    try:
        with pg.connect().execution_options(isolation_level="AUTOCOMMIT") as owner:
            owner.execute(text(f'CREATE DATABASE "{name}" TEMPLATE template0'))
        created = True
        database = create_engine(pg.url.set(database=name))
        monkeypatch.setenv("ONESA_DATABASE_URL", database.url.render_as_string(hide_password=False))
        yield database
    finally:
        if database is not None:
            database.dispose()
        if created:
            # The name is generated by this fixture and CREATE succeeded here.
            # Do not terminate connections or drop any pre-existing database.
            with pg.connect().execution_options(isolation_level="AUTOCOMMIT") as owner:
                owner.execute(text(f'DROP DATABASE "{name}"'))


@pytest.mark.parametrize(
    "revision,features",
    [
        ("20261010_capacity", []),
        ("20261025_twins", ["twins"]),
        ("20261026_cybersecurity", ["cybersecurity"]),
        ("20261026_cybersecurity", ["cybersecurity", "twins"]),
    ],
)
def test_native_bridge_runs_before_and_after_actual_identity_migration(
    bridge_database, tmp_path, revision, features
):
    """Current source keeps native auth/data valid on both sides of the upgrade.

    Qualifying the flag-off image does not require migrating its hosted database
    early. The independent identity profile still needs its own accepted owner
    chain and exact-image synthetic restore proof before activation.
    """
    config = Config(str(Path(__file__).parents[1] / "alembic.ini"))
    command.upgrade(config, revision)
    absent = {"shared_identities", "identity_sessions", "identity_transactions"}
    assert absent.isdisjoint(inspect(bridge_database).get_table_names())
    with bridge_database.connect() as connection:
        assert connection.scalar(text("SELECT version_num FROM alembic_version")) == revision
    settings = Settings(
        environment="test",
        database_url=bridge_database.url.render_as_string(hide_password=False),
        model_backend="mock",
        embedding_backend="lexical",
        identity_enabled=False,
        digital_twins_enabled="twins" in features,
        cybersecurity_enabled="cybersecurity" in features,
        digital_twins_storage_directory=str(tmp_path),
        registration_mode="open",
        public_origin="http://localhost:3100",
        auth_rate_limit=100,
    )
    exercise = workflow()
    seeded = exercise(settings, {"phase": "seed", "enabled_features": features, "fixture": None})
    request = {"phase": "verify", "enabled_features": features, "fixture": seeded["fixture"]}
    before = exercise(settings, request)
    with bridge_database.connect() as connection:
        users = connection.execute(
            text("SELECT id, email, password_hash FROM users ORDER BY id")
        ).all()
    # Readiness remains strict when shared identity is enabled. This probe only
    # reads the local database; it does not contact the synthetic issuer.
    identity_settings = Settings(
        **{
            **settings.model_dump(),
            "identity_enabled": True,
            "identity_issuer": "http://localhost:3101/api/v1/identity",
            "identity_client_id": "onesa-ai-bridge-test",
            "identity_client_secret": "synthetic-bridge-client-secret-for-tests-only",
            "identity_callback_url": settings.public_origin + "/api/v1/auth/onesa/callback",
            "identity_encryption_key": Fernet.generate_key().decode(),
        }
    )
    with TestClient(create_app(identity_settings)) as client:
        assert client.get("/core-ready").status_code == 503

    command.upgrade(config, REQUIRED_SCHEMA_REVISION)
    with bridge_database.connect() as connection:
        assert (
            connection.scalar(text("SELECT version_num FROM alembic_version"))
            == REQUIRED_SCHEMA_REVISION
        )
    after = exercise(settings, request)
    assert before == after
    with bridge_database.connect() as connection:
        assert (
            connection.execute(text("SELECT id, email, password_hash FROM users ORDER BY id")).all()
            == users
        )
        assert connection.scalar(text("SELECT count(*) FROM conversations")) == 1
        for table in sorted(absent):
            assert connection.scalar(text(f"SELECT count(*) FROM {table}")) == 0
    with TestClient(create_app(identity_settings)) as client:
        assert client.get("/core-ready").status_code == 200


@pytest.mark.parametrize("features", [[], ["twins"], ["cybersecurity"], ["cybersecurity", "twins"]])
def test_retained_runtime_workflows_preserve_all_native_flag_combinations(pg, tmp_path, features):
    with pg.begin() as connection:
        connection.execute(text("TRUNCATE users, rate_buckets CASCADE"))
    settings = Settings(
        environment="test",
        database_url=pg.url.render_as_string(hide_password=False),
        model_backend="mock",
        embedding_backend="lexical",
        identity_enabled=False,
        digital_twins_enabled="twins" in features,
        cybersecurity_enabled="cybersecurity" in features,
        digital_twins_storage_directory=str(tmp_path),
        registration_mode="open",
        public_origin="http://localhost:3100",
        auth_rate_limit=100,
    )
    exercise = workflow()
    seeded = exercise(settings, {"phase": "seed", "enabled_features": features, "fixture": None})
    verified = exercise(
        settings, {"phase": "verify", "enabled_features": features, "fixture": seeded["fixture"]}
    )
    assert verified == {
        "enabled_features": features,
        "identity_enabled": False,
        "checks": {
            "core_readiness": "PASS",
            "local_authentication": "PASS",
            "ordinary_workflows": "PASS",
            "native_features": "PASS",
        },
    }
    with pg.connect() as connection:
        assert connection.scalar(text("SELECT count(*) FROM users")) == 2
        assert connection.scalar(text("SELECT count(*) FROM conversations")) == 1
        assert connection.scalar(text("SELECT count(*) FROM shared_identities")) == 0
        assert connection.scalar(text("SELECT count(*) FROM identity_sessions")) == 0
