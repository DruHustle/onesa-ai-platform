"""Hash-lock the tested macOS dependency graph from official PyPI release metadata.

This uses installed distributions, avoiding re-resolution to untested versions.
Only metadata is fetched; no model, executable or package artifact is downloaded.
"""

import hashlib
import importlib.metadata
import json
import platform
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name


def main() -> None:
    if (
        platform.system() != "Darwin"
        or platform.machine() != "arm64"
        or sys.version_info[:2] != (3, 11)
    ):
        raise SystemExit("This qualified runtime lock requires macOS arm64 / Python 3.11")
    pending = ["sentence-transformers", "torch", "fastapi", "uvicorn", "pip", "setuptools"]
    versions = {}
    while pending:
        name = canonicalize_name(pending.pop())
        if name in versions:
            continue
        distribution = importlib.metadata.distribution(name)
        versions[name] = distribution.version
        for raw in distribution.requires or []:
            requirement = Requirement(raw)
            if requirement.marker and not requirement.marker.evaluate({"extra": ""}):
                continue
            child = canonicalize_name(requirement.name)
            installed = importlib.metadata.version(child)
            if requirement.specifier and installed not in requirement.specifier:
                raise RuntimeError("Installed graph violates dependency requirements")
            pending.append(child)

    def release(name):
        url = f"https://pypi.org/pypi/{name}/{versions[name]}/json"
        with urllib.request.urlopen(url, timeout=30) as response:
            payload = json.load(response)
        hashes = sorted({file["digests"]["sha256"] for file in payload["urls"]})
        if not hashes or any(len(value) != 64 for value in hashes):
            raise RuntimeError("Official release hashes missing")
        return name, hashes

    with ThreadPoolExecutor(max_workers=4) as pool:
        releases = dict(pool.map(release, sorted(versions)))
    output = Path(__file__).with_name("requirements-macos.lock")
    lines = [
        "# Tested macOS arm64 / Python 3.11 runtime; not a Linux lock.",
        "# Generated by python -m embedding_service.lock_installed from installed versions.",
        "# SHA-256 hashes from official PyPI HTTPS release metadata.",
    ]
    for name in sorted(versions):
        lines.append(f"{name}=={versions[name]} \\")
        hashes = releases[name]
        for index, value in enumerate(hashes):
            lines.append("    --hash=sha256:" + value + (" \\" if index < len(hashes) - 1 else ""))
    output.write_text("\n".join(lines) + "\n")
    print(
        f"Locked {len(versions)} tested distributions; "
        f"sha256 {hashlib.sha256(output.read_bytes()).hexdigest()}"
    )


if __name__ == "__main__":
    main()
