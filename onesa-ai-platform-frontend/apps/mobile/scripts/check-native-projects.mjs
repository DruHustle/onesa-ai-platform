import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const read = path => readFile(new URL('../' + path, import.meta.url), 'utf8');
const { expo } = JSON.parse(await read('app.json'));
assert.equal(expo.ios.bundleIdentifier, 'eu.onesa.aiplatform');
assert.equal(expo.android.package, 'eu.onesa.aiplatform');
const project = await read('ios/OnesaAIPlatform.xcodeproj/project.pbxproj');
assert.match(project, /PRODUCT_BUNDLE_IDENTIFIER = "?eu\.onesa\.aiplatform"?;/);
assert.match(project, /PRODUCT_NAME = "OnesaAIPlatform";/);
const plist = await read('ios/OnesaAIPlatform/Info.plist');
assert.match(plist, /<string>onesaai<\/string>/);
assert.doesNotMatch(plist, /NSAllowsArbitraryLoads<\/key>\s*<true/);
const gradle = await read('android/app/build.gradle');
assert.match(gradle, /applicationId\s+["']eu\.onesa\.aiplatform["']/);
const manifest = await read('android/app/src/main/AndroidManifest.xml');
assert.match(manifest, /android:scheme="onesaai"/);
assert.doesNotMatch(manifest, /android:usesCleartextTraffic="true"/);
assert.equal(expo.updates.enabled, false);
console.log('Generated iOS/Android IDs, callback scheme and transport policy verified.');
